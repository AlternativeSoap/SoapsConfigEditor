import { yamlQuoted } from '../generators'
import type {
  DialogBubble,
  DialogCompileResult,
  DialogEdge,
  DialogGraph,
  DialogOption,
} from './types'
import { sanitizeDialogId } from './types'

function glueSkillId(graphId: string, fromDialogId: string, optionKey: string): string {
  return sanitizeDialogId(`${graphId}_${fromDialogId}_${optionKey}_Next`)
}

function resolveOptionSkill(
  graph: DialogGraph,
  bubble: DialogBubble,
  option: DialogOption,
  edges: DialogEdge[],
): { skillId: string | null; glueYaml: string | null } {
  if (option.skillId?.trim()) {
    return { skillId: option.skillId.trim(), glueYaml: null }
  }
  const edge = edges.find((e) => e.fromBubbleId === bubble.id && e.optionKey === option.key)
  if (!edge) {
    return { skillId: null, glueYaml: null }
  }
  const target = graph.nodes.find((n) => n.id === edge.toBubbleId)
  if (!target) return { skillId: null, glueYaml: null }

  const skillId = glueSkillId(graph.graphId, bubble.dialogId, option.key)
  const glueYaml = `${skillId}:
  Skills:
  - showdialog{dialog=${target.dialogId}} @trigger
`
  return { skillId, glueYaml }
}

function emitBubbleYaml(
  bubble: DialogBubble,
  graph: DialogGraph,
  glueParts: string[],
): string {
  const lines: string[] = [`${bubble.dialogId}:`]
  lines.push(`  Title: ${yamlQuoted(bubble.title)}`)
  if (bubble.externalTitle?.trim()) {
    lines.push(`  ExternalTitle: ${yamlQuoted(bubble.externalTitle.trim())}`)
  }
  lines.push(`  CanClose: ${bubble.canClose}`)
  lines.push(`  Pause: ${bubble.pause}`)
  lines.push(`  AfterAction: ${bubble.afterAction}`)
  if (bubble.columns > 1) lines.push(`  Columns: ${bubble.columns}`)

  if (bubble.body.length > 0) {
    lines.push('  Body:')
    for (const el of bubble.body) {
      if (el.type === 'text') {
        lines.push('  - Type: text')
        lines.push(`    Message: ${yamlQuoted(el.message)}`)
        if (el.width != null) lines.push(`    Width: ${el.width}`)
      } else {
        lines.push('  - Type: item')
        lines.push(`    Item: ${el.item}`)
        if (el.width != null) lines.push(`    Width: ${el.width}`)
        if (el.height != null) lines.push(`    Height: ${el.height}`)
        if (el.showTooltip) lines.push('    ShowTooltip: true')
      }
    }
  }

  if (bubble.options.length > 0) {
    lines.push('  Buttons:')
    for (const opt of bubble.options) {
      const { skillId, glueYaml } = resolveOptionSkill(graph, bubble, opt, graph.edges)
      if (glueYaml) glueParts.push(glueYaml)
      lines.push(`  - Label: ${yamlQuoted(opt.label)}`)
      if (opt.tooltip?.trim()) lines.push(`    Tooltip: ${yamlQuoted(opt.tooltip.trim())}`)
      lines.push(`    Width: ${opt.width ?? 150}`)
      if (skillId) lines.push(`    Skill: ${skillId}`)
    }
  }

  const exit = bubble.exitButton
  if (exit?.label?.trim()) {
    lines.push('  ExitButton:')
    lines.push(`    Label: ${yamlQuoted(exit.label.trim())}`)
    lines.push(`    Width: ${exit.width ?? 100}`)
    if (exit.skillId?.trim()) lines.push(`    Skill: ${exit.skillId.trim()}`)
  }

  return lines.join('\n') + '\n'
}

/** Compile a dialog graph into Mythic Dialogs YAML + glue skills YAML. */
export function compileDialogGraph(graph: DialogGraph): DialogCompileResult {
  const glueParts: string[] = []
  const dialogBlocks = graph.nodes.map((n) => emitBubbleYaml(n, graph, glueParts))
  const dialogYaml =
    `# Generated by Soaps Dialog workplace\n` +
    `# Requires MythicMobs Premium and Paper 1.21.6+\n\n` +
    dialogBlocks.join('\n')

  const skillsYaml =
    glueParts.length === 0
      ? `# No dialog link skills for ${graph.graphId}\n`
      : `# Auto-generated dialog link skills for ${graph.graphId}\n\n` + glueParts.join('\n')

  const stem = sanitizeDialogId(graph.graphId).toLowerCase()
  const entry = graph.entryBubbleId
    ? graph.nodes.find((n) => n.id === graph.entryBubbleId) ?? graph.nodes[0]
    : graph.nodes[0]
  const entryDialogId = entry?.dialogId ?? null

  return {
    dialogYaml,
    skillsYaml,
    dialogFileName: `${stem}-dialogs.yml`,
    skillsFileName: `${stem}-dialog-skills.yml`,
    entryDialogId,
    attachSkillLine: entryDialogId
      ? `showdialog{dialog=${entryDialogId}} @trigger ~onInteract`
      : null,
  }
}

